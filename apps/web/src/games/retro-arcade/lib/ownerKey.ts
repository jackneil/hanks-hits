/**
 * Save states stay on the device, one partition for each player, so a kid on
 * a shared family iPad never loads the save of another account.
 *
 * A signed-in player gets "u_" + the first 20 hex characters of
 * SHA-256("hh-retro-states:v1:" + userId). A player who is not signed in gets
 * "guest". The raw user id never goes into storage.
 */

export const GUEST_OWNER = "guest";
export const OWNER_SALT = "hh-retro-states:v1:";

const OWNER_PATTERN = /^(guest|u_[0-9a-f]{20})$/;

/** True when the value is a valid owner key. */
export function isOwnerKey(value: unknown): value is string {
  return typeof value === "string" && OWNER_PATTERN.test(value);
}

function toHex(bytes: Uint8Array): string {
  let hex = "";
  for (const byte of bytes) hex += byte.toString(16).padStart(2, "0");
  return hex;
}

